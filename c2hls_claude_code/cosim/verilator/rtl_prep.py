"""Prepare Vitis HLS RTL for Verilator: Python port of TAPA's Verilator fast-cosim RTL preparation.

Ported from github.com/tuna/tapa (MIT, "TAPA community maintainers and contributors"),
fpga-runtime/frt-cosim/src/runner/verilator.rs at commit d249ff9 (2026-09-21):
  * generate_xilinx_fp_ip_models / parse_xilinx_fp_ip_tcl_text / generate_xilinx_fp_ip_replacement:
    every instantiated `<name>_ip` module whose `<name>_ip.tcl` is `create_ip -name floating_point` gets a
    behavioral SystemVerilog stand-in with the same AXI-Stream ports and a `c_latency`-deep pipeline; the
    arithmetic is a DPI-C call (fp_dpi.c). Only fp32/fp64 add/sub/mul are covered, as in TAPA.
  * rewrite_combinational_nba: `<=` inside `always @(*)` blocks becomes `=` (Verilator would otherwise warn and
    convert it itself).
Difference from TAPA: the DPI functions in fp_dpi.c flush subnormal inputs/outputs to zero, as AMD's
floating-point cores do (TAPA's Rust DPI uses plain IEEE f32/f64 ops).
"""
from __future__ import annotations

import re
from pathlib import Path

IP_RE = re.compile(r"(?m)^\s*(\w+_ip)\s+\w+\s*\(")
CONFIG_RE = re.compile(r"CONFIG\.([A-Za-z0-9_]+)\s+([^\s\\]+)")
NBA_RE = re.compile(r"^(\s+\w+)\s*<=\s*(.+;)$")
INLINE_NBA_RE = re.compile(r"@\(\*\)\s*(\w+)\s*<=")
BEGIN_RE = re.compile(r"\bbegin\b")
END_RE = re.compile(r"\bend\b")


def is_verilog_like(p: Path) -> bool:
    return p.suffix in (".v", ".sv", ".vh")


def parse_fp_ip_tcl(text: str):
    """(dpi_func, latency) for a floating_point IP tcl, or None if unsupported."""
    if "create_ip -name floating_point" not in text:
        return None
    cfg = {m.group(1): m.group(2) for m in CONFIG_RE.finditer(text)}
    is_double = cfg.get("a_precision_type", "single").lower() == "double"
    op_type = cfg.get("operation_type", "").lower()
    if "multiply" in op_type:
        op = "mul"
    elif "add" in op_type or "subtract" in op_type:
        op = "sub" if cfg.get("add_sub_value", "").lower() in ("subtract", "sub") else "add"
    else:
        return None
    if "c_latency" not in cfg:
        raise ValueError("FP IP TCL missing CONFIG.c_latency")
    return (f"fp{64 if is_double else 32}_{op}", int(cfg["c_latency"]))


def fp_ip_model(ip_module: str, dpi_func: str, latency: int) -> str:
    width = 64 if "64" in dpi_func else 32
    hi = width - 1
    ret = "longint unsigned" if width == 64 else "int unsigned"
    head = f"""`timescale 1ns/1ps
// Behavioral stand-in for AMD floating_point IP {ip_module} (latency {latency}), generated by rtl_prep.py
// (port of TAPA frt-cosim). Arithmetic: DPI-C {dpi_func} in fp_dpi.c.
module {ip_module} (
    input  wire        aclk,
    input  wire        aclken,
    input  wire        s_axis_a_tvalid,
    input  wire [{hi}:0] s_axis_a_tdata,
    input  wire        s_axis_b_tvalid,
    input  wire [{hi}:0] s_axis_b_tdata,
    output wire        m_axis_result_tvalid,
    output wire [{hi}:0] m_axis_result_tdata
);

import "DPI-C" function {ret} {dpi_func}(input {ret} a, input {ret} b);
"""
    if latency == 0:
        return head + f"""
assign m_axis_result_tdata = {dpi_func}(s_axis_a_tdata, s_axis_b_tdata);
assign m_axis_result_tvalid = s_axis_a_tvalid & s_axis_b_tvalid;

endmodule
"""
    d = latency - 1
    return head + f"""
reg [{hi}:0] pipe [0:{d}];
reg [{d}:0]  valid_pipe;

integer i;

always @(posedge aclk) begin
    if (aclken) begin
        pipe[0] <= {dpi_func}(s_axis_a_tdata, s_axis_b_tdata);
        valid_pipe[0] <= s_axis_a_tvalid & s_axis_b_tvalid;
        for (i = 1; i < {latency}; i = i + 1) begin
            pipe[i] <= pipe[i-1];
            valid_pipe[i] <= valid_pipe[i-1];
        end
    end
end

assign m_axis_result_tdata  = pipe[{d}];
assign m_axis_result_tvalid = valid_pipe[{d}];

endmodule
"""


def generate_fp_ip_models(rtl_dir: Path) -> dict:
    """Write <ip>.sv for every instantiated floating-point IP. Returns {ip: (dpi_func, latency) | 'unsupported'}."""
    done = {}
    for path in sorted(rtl_dir.iterdir()):
        if not is_verilog_like(path):
            continue
        for ip in IP_RE.findall(path.read_text(errors="replace")):
            if ip in done:
                continue
            existing = [rtl_dir / f"{ip}.v", rtl_dir / f"{ip}.sv"]
            if any(p.exists() and "`pragma protect" not in p.read_text(errors="replace") for p in existing):
                done[ip] = "existing"
                continue
            tcl = rtl_dir / f"{ip}.tcl"
            model = parse_fp_ip_tcl(tcl.read_text()) if tcl.exists() else None
            if model is None:
                done[ip] = "unsupported"
                continue
            (rtl_dir / f"{ip}.sv").write_text(fp_ip_model(ip, *model))
            done[ip] = model
    return done


def rewrite_combinational_nba(content: str) -> str:
    out, state, depth = [], "outside", 0
    for line in content.splitlines():
        code = line.split("//")[0]
        trimmed = code.strip()
        rewrite = False
        if state == "block":
            rewrite = True
            depth += len(BEGIN_RE.findall(code)) - len(END_RE.findall(code))
            if depth <= 0:
                state = "outside"
        elif state == "statement":
            rewrite = True
            if ";" in code:
                state = "outside"
        elif trimmed.startswith("always") and "@(*)" in trimmed:
            depth = len(BEGIN_RE.findall(code)) - len(END_RE.findall(code))
            if depth > 0:
                state = "block"
            elif ";" in code:
                rewrite = True
            else:
                state = "statement"
        if rewrite:
            if NBA_RE.match(line):
                line = NBA_RE.sub(r"\1 = \2", line)
            elif trimmed.startswith("always"):
                line = INLINE_NBA_RE.sub(r"@(*) \1 =", line)
        out.append(line)
    return "\n".join(out) + "\n"


def fix_combinational_nba(rtl_dir: Path) -> int:
    changed = 0
    for path in rtl_dir.iterdir():
        if not is_verilog_like(path):
            continue
        text = path.read_text(errors="replace")
        if "always @(*)" not in text:
            continue
        new = rewrite_combinational_nba(text)
        if new != text:
            path.write_text(new)
            changed += 1
    return changed
