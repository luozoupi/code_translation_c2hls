#!/usr/bin/env python3
"""Writes apply_frp_fir.sh: fork patches 0004-0007 embedded, for Fir (no ssh from Otus, MFA).

  python3 make_apply_fir.py EXPECT.json      EXPECT.json: {design: expected end} for the validation job (Otus fix7 run)
"""
import json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PATCHES = sorted((HERE / "fork_patches").glob("000[4-7]-*.patch"))
assert [p.name[:4] for p in PATCHES] == ["0004", "0005", "0006", "0007"], PATCHES
expect = json.loads(Path(sys.argv[1]).read_text())
PRE = "da0dae7ff11104eb2b138e07794ed4b4676a1c01"     # 3 m_axi commits (Fir's install)
MID = "6c1cbd549ab1037cc654833dab08a220ebf09df5"     # + 0004 (if the earlier apply_frp_fir.sh was run)
POST = (HERE / "fork_tree.txt").read_text().strip()  # + 0005..0007

embedded = "\n".join(
    f"  cat > \"$T/tmp/{p.name}\" <<'EOF_PATCH_{p.name[:4]}'\n{p.read_text()}EOF_PATCH_{p.name[:4]}" for p in PATCHES)
only = ":".join(expect)
checks = "\n".join(f"echo \"  grep -h '\\\"end\\\"' $ROOT/{d}/lsim_fixfir.json   # expect {e}\"" for d, e in expect.items())

script = f"""#!/bin/bash
# apply_frp_fir.sh : put fork patches 0004-0007 into Fir's LightningSim and reinstall it (generated by make_apply_fir.py).
#   0004 FRP read-after-write +1 (superseded by 0006), 0005 empty() in the testbench runtime, 0006 FRP issue/depth/no-freeze,
#   0007 polled reads (empty() before read) do not freeze a stall pipeline.
# Run on a Fir login node:   bash apply_frp_fir.sh
# 1. checks that no LightningSim job runs and the fork tree is the 3 m_axi commits ({PRE[:8]}) or that plus 0004 ({MID[:8]});
# 2. backs up the installed package and runtime templates to $T/tmp/*_backup_pre_fix_<date>;
# 3. git am the embedded patches, checks the tree is Otus's ({POST[:8]}), rebuilds the Rust core, reinstalls, rebuilds
#    the testbench runtime (liblightningsimrt.a, fifo.ll.jinja) into env/share/lightningsim/templates;
# 4. submits one validation job ({only}) unless VALIDATE=0.
# Undo: cp -a the backups back, and git -C $T/src reset --hard <the commit printed before git am>.
set -euo pipefail
T=/scratch/asa582/tools/lightningsim
TMPB=/scratch/asa582/tmp/c2hls/lsim
LSIMDIR=/scratch/asa582/workspaces/c2hls_claude_code/cosim/lsim
ROOT=${{ROOT:-$TMPB/soda}}
PRE={PRE}
MID={MID}
POST={POST}
stamp=$(date +%Y%m%d_%H%M)

if squeue -u "$USER" -h -t R -o '%j' | grep -q lsim; then
  echo "a LightningSim job is running on Fir; reinstalling now could break it. Try again when it ends:"; squeue -u "$USER" -t R | grep lsim; exit 1
fi
TREE=$(git -C "$T/src" rev-parse 'HEAD^{{tree}}')
if [ "$TREE" = "$POST" ]; then echo "fork already has patches 0004-0007 (tree $POST); only reinstalling"
else
  case "$TREE" in
    "$PRE") FIRST=0004 ;;
    "$MID") FIRST=0005 ;;
    *) echo "fork tree $TREE is neither $PRE (3 m_axi commits) nor $MID (+0004); stop"; exit 1 ;;
  esac
  [ -z "$(git -C "$T/src" status --porcelain --untracked-files=no)" ] || {{ echo "fork has local changes:"; git -C "$T/src" status --short; exit 1; }}
  mkdir -p "$T/tmp"
{embedded}
  echo "fork before: $(git -C "$T/src" rev-parse HEAD)"
  for p in "$T"/tmp/000[4-7]-*.patch; do
    [ "$(basename "$p" | cut -c1-4)" \\< "$FIRST" ] && continue
    git -C "$T/src" -c user.name="$USER" -c user.email="$USER@localhost" am "$p"
  done
  TREE=$(git -C "$T/src" rev-parse 'HEAD^{{tree}}')
  [ "$TREE" = "$POST" ] || {{ echo "after git am the tree is $TREE, expected $POST; stop"; exit 1; }}
  echo "fork patched: $(git -C "$T/src" log --oneline -1)"
fi

SITE=$("$T/env/bin/python" -c 'import lightningsim, os; print(os.path.dirname(lightningsim.__file__))')
TPL="$T/env/share/lightningsim/templates"
cp -a "$SITE" "$T/tmp/lightningsim_site_backup_pre_fix_$stamp"; echo "backup of $SITE -> $T/tmp/lightningsim_site_backup_pre_fix_$stamp"
cp -a "$TPL" "$T/tmp/templates_backup_pre_fix_$stamp"; echo "backup of $TPL -> $T/tmp/templates_backup_pre_fix_$stamp"

# same steps as cosim/lsim/build_lsim.sh, with Fir paths
export PATH="$T/rustenv/bin:$T/env/bin:$PATH"
export CARGO_HOME="$T/cargo" CARGO_TARGET_DIR="$TMPB/cargo-target" TMPDIR="$TMPB/tmp"
unset PYTHONPATH PIP_CONFIG_FILE
mkdir -p "$TMPDIR"
cd "$T/src/backend"
sed -i "s#^CONDA_PREFIX = Path(r\\"\\"\\"[^\\"]*\\"\\"\\")#CONDA_PREFIX = Path(r\\"\\"\\"$T/env\\"\\"\\")#" lightningsim/runner.py
"$T/env/bin/python" -m pip install --no-deps --no-build-isolation --ignore-installed . 2>&1 | tail -n 3
sed -i "s#^CONDA_PREFIX = Path(r\\"\\"\\"$T/env\\"\\"\\")#CONDA_PREFIX = Path(r\\"\\"\\"/opt/anaconda1anaconda2anaconda3\\"\\"\\")#" lightningsim/runner.py
# testbench runtime (0005)
mkdir -p "$TMPB/templates_build"
make -s -C "$T/src" CXX=x86_64-conda-linux-gnu-g++ AR=x86_64-conda-linux-gnu-ar DESTDIR="$TMPB/templates_build"
cp "$TMPB/templates_build"/{{liblightningsimrt.a,fifo.ll.jinja,m_axi.ll.jinja}} "$TPL/"
cd /
"$T/env/bin/python" - <<'EOF'
import inspect, lightningsim._core as c, lightningsim.runner as r, lightningsim.frp as f
assert hasattr(f, "pipeline_polls") and hasattr(f, "frp_params"), "frp.py is not 0007's"
assert b"anchor_freeze" in open(c.__file__, "rb").read(), "Rust core was not rebuilt with anchor_freeze"
print("installed with patches 0004-0007:", c.__file__, r.CONDA_PREFIX)
EOF
grep -q _autotb_FifoCanRead "$TPL/fifo.ll.jinja" && echo "runtime templates have _autotb_FifoCanRead"

[ "${{VALIDATE:-1}}" = 1 ] || exit 0
for n in {" ".join(expect)}; do [ -f "$ROOT/$n/proj.tar.gz" ] || {{ echo "no $ROOT/$n/proj.tar.gz; skip the validation job (set ROOT=...)"; exit 0; }}; done
J=$(sbatch --parsable --mem=128G --export=ALL,ROOT="$ROOT",ONLY={only},TAG=fixfir,PAR={len(expect)} "$LSIMDIR/sbatch_lsim.sh")
echo "validation job $J. When it ends:"
{checks}
"""
out = HERE / "apply_frp_fir.sh"
out.write_text(script)
out.chmod(0o755)
print("wrote", out, len(script), "bytes;", ", ".join(p.name for p in PATCHES))
