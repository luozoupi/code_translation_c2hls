#!/usr/bin/env python3
"""Materialize benchmarks_cosim/ — cosim-ready HLSFactory baselines without touching benchmarks/."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
REPO = SCRIPT_DIR.parent
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from scripts.cosim_interface_pragmas import (  # noqa: E402
    DOITGEN_BODY_OVERRIDE,
    TWO_MM_BODY_OVERRIDE,
    inject_cosim_interfaces,
    strip_hls_pragmas_only,
)

SRC_ROOT = REPO / "benchmarks"
OUT_ROOT = REPO / "benchmarks_cosim"
COSIM_KERNEL_FILE = "hls_baseline_cosim.cpp"
GOLD_HLS_SOURCE_FILE = "gold_hls_source.cpp"

SYMLINK_NAMES = (
    "testbench.cpp",
    "testbench_cosim.cpp",
    "gold_kernel_for_cosim.cpp",
    "hls_baseline.cpp",
)

# Per-bench problem size N (full cosim) and optional m_axi depth overrides.
_BENCH_N: dict[str, int] = {}
_PORT_DEPTHS: dict[str, dict[str, int]] = {
    "hlsfactory_doitgen": {"A": 25 * 20 * 30, "C4": 30 * 30, "sum": 30},
}


def _read_n_from_header(header_path: Path) -> int:
    if not header_path.exists():
        return 120
    text = header_path.read_text()
    match = re.search(r"#define\s+N\s+(\d+)", text)
    return int(match.group(1)) if match else 120


def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _symlink_or_copy(src: Path, dst: Path) -> None:
    if dst.exists() or dst.is_symlink():
        dst.unlink()
    os.symlink(src.resolve(), dst)


def _gold_hls_source_from_cosim(cosim_src: str) -> str:
    """Cosim gold oracle: identical body to hls_baseline_cosim.cpp (interfaces included)."""
    header = (
        "// AUTO-GENERATED by prepare_hlsfactory_cosim_benchmarks.py — do not edit.\n"
        "// Same source as hls_baseline_cosim.cpp; included as kernel_*_gold via\n"
        "// gold_kernel_for_cosim.cpp for cosim pre-check.\n\n"
    )
    body = cosim_src if cosim_src.endswith("\n") else cosim_src + "\n"
    return header + body


def _cosim_kernel_source(bench: str, baseline_cpp: Path, header_path: Path) -> str:
    if bench == "hlsfactory_doitgen":
        return DOITGEN_BODY_OVERRIDE
    if bench == "hlsfactory_2mm":
        return TWO_MM_BODY_OVERRIDE
    n = _BENCH_N.get(bench, _read_n_from_header(header_path))
    depths = _PORT_DEPTHS.get(bench)
    return inject_cosim_interfaces(
        baseline_cpp.read_text(),
        n=n,
        port_depths=depths,
        bundle_per_port=True,
    )


def prepare_one(src_dir: Path, out_dir: Path, *, dry_run: bool = False) -> dict:
    bench = src_dir.name
    meta_src = json.loads((src_dir / "metadata.json").read_text())
    header_name = meta_src.get("header_file", "")
    header_path = src_dir / header_name if header_name else src_dir

    if not dry_run:
        out_dir.mkdir(parents=True, exist_ok=True)

    actions: list[str] = []
    for name in SYMLINK_NAMES:
        src = src_dir / name
        if not src.exists():
            continue
        actions.append(f"symlink {name}")
        if not dry_run:
            _symlink_or_copy(src, out_dir / name)

    for name in (header_name,):
        if not name:
            continue
        src = src_dir / name
        if src.exists():
            actions.append(f"symlink {name}")
            if not dry_run:
                _symlink_or_copy(src, out_dir / name)

    baseline_cpp = src_dir / meta_src.get("gold_hls_baseline_file", "hls_baseline.cpp")
    cosim_src = _cosim_kernel_source(bench, baseline_cpp, header_path)
    actions.append(f"write {COSIM_KERNEL_FILE}")
    plain_code, plain_strip = strip_hls_pragmas_only(cosim_src)
    gold_code = _gold_hls_source_from_cosim(cosim_src)
    actions.append(f"write {GOLD_HLS_SOURCE_FILE}")
    actions.append("write plain.cpp")
    if not dry_run:
        (out_dir / COSIM_KERNEL_FILE).write_text(cosim_src)
        plain_path = out_dir / "plain.cpp"
        if plain_path.exists() or plain_path.is_symlink():
            plain_path.unlink()
        plain_path.write_text(plain_code + ("\n" if plain_code and not plain_code.endswith("\n") else ""))
        gold_path = out_dir / GOLD_HLS_SOURCE_FILE
        if gold_path.exists() or gold_path.is_symlink():
            gold_path.unlink()
        gold_path.write_text(gold_code)

    meta = dict(meta_src)
    meta["corpus"] = "benchmarks_cosim"
    meta["parent_benchmark"] = bench
    meta["parent_benchmark_dir"] = str(src_dir.relative_to(REPO))
    meta["cosim_kernel_file"] = COSIM_KERNEL_FILE
    meta["cosim_interface_variant"] = "explicit_m_axi_per_port"
    meta["plain_c_file"] = "plain.cpp"
    meta["plain_derived_from"] = COSIM_KERNEL_FILE
    meta["gold_derived_from"] = COSIM_KERNEL_FILE
    meta["cosim_plain_strip_report"] = plain_strip
    provenance = dict(meta.get("provenance") or {})
    provenance["plain_c_sha256"] = _sha256(plain_code)
    provenance["plain_derived_from_cosim_kernel"] = True
    provenance["gold_hls_source_sha256"] = _sha256(gold_code)
    provenance["gold_derived_from_cosim_kernel"] = True
    meta["provenance"] = provenance
    actions.append("write metadata.json")
    if not dry_run:
        (out_dir / "metadata.json").write_text(json.dumps(meta, indent=2) + "\n")

    return {"bench": bench, "out_dir": str(out_dir), "actions": actions}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bench", action="append", default=[], help="Limit to bench dir name")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    bench_filter = set(args.bench) if args.bench else None
    summary = []
    for src_dir in sorted(SRC_ROOT.glob("hlsfactory_*")):
        if bench_filter and src_dir.name not in bench_filter:
            continue
        meta_path = src_dir / "metadata.json"
        if not meta_path.exists():
            continue
        meta = json.loads(meta_path.read_text())
        if not meta.get("supports_cosim"):
            continue
        out_dir = OUT_ROOT / src_dir.name
        summary.append(prepare_one(src_dir, out_dir, dry_run=args.dry_run))

    print(json.dumps({"out_root": str(OUT_ROOT), "count": len(summary), "benches": summary}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
