"""Generate the Verilator C++ testbench for a Vitis HLS kernel (vitis flow: s_axi_control + m_axi bundles).

The AXI memory model, reset sequence and AXI-Lite start sequence are ported from TAPA's
fpga-runtime/frt-cosim/templates/tb_verilator.cpp.j2 (github.com/tuna/tapa, MIT, commit d249ff9): one flat memory
per m_axi bundle, up to 16 outstanding reads/writes per port, bursts served one beat per cycle, write strobes
honoured, GIE/IER enabled and done detected on `interrupt`.
Additions: memories are loaded from / dumped to raw files instead of TAPA shared memory; a clock-edge cycle counter,
heartbeat (cycles, wall time, cycles/s) and a cycle limit; an early check of C as it is written (compared with the
golden; disabled automatically when the kernel reads C or writes an address twice, since writes are then not final).
"""
from __future__ import annotations


def axi_block(b: str, idx: int, nbytes: int) -> str:
    p = f"dut->m_axi_{b}_"
    return f"""
  // ---- bundle {b} ----
  {p}ARREADY = (int(rd_q[{idx}].size()) < kMaxOutstanding) ? 1 : 0;
  if ({p}ARVALID && {p}ARREADY) {{
    rd_q[{idx}].push_back({{(uint64_t){p}ARADDR, (uint8_t){p}ARLEN, (uint32_t){p}ARID, 0}});
    if ({idx} == kCIdx) c_was_read = true;
  }}
  if (!rd_q[{idx}].empty()) {{
    auto& r = rd_q[{idx}].front();
    {p}RVALID = 1;
    mem[{idx}]->read(r.addr + (uint64_t)r.beat * {nbytes}, &{p}RDATA, {nbytes});
    {p}RLAST = (r.beat == r.len) ? 1 : 0;
    {p}RID = r.id;
    {p}RRESP = 0;
    if ({p}RREADY) {{ if (r.beat >= r.len) rd_q[{idx}].pop_front(); else r.beat++; }}
  }} else {{
    {p}RVALID = 0;
  }}
  {p}AWREADY = (int(wr_q[{idx}].size()) < kMaxOutstanding) ? 1 : 0;
  if ({p}AWVALID && {p}AWREADY) wr_q[{idx}].push_back({{(uint64_t){p}AWADDR, (uint32_t){p}AWID, 0}});
  {p}WREADY = !wr_q[{idx}].empty() ? 1 : 0;
  if ({p}WVALID && {p}WREADY && !wr_q[{idx}].empty()) {{
    auto& w = wr_q[{idx}].front();
    const uint64_t a = w.addr + (uint64_t)w.beat * {nbytes};
    mem[{idx}]->write(a, &{p}WDATA, &{p}WSTRB, {nbytes});
    if ({idx} == kCIdx) check_c_write(a, &{p}WSTRB, {nbytes});
    w.beat++;
    if ({p}WLAST) {{ b_q[{idx}].push_back(w.id); wr_q[{idx}].pop_front(); }}
  }}
  if (!b_q[{idx}].empty()) {{
    {p}BVALID = 1; {p}BID = b_q[{idx}].front(); {p}BRESP = 0;
    if ({p}BREADY) b_q[{idx}].pop_front();
  }} else {{
    {p}BVALID = 0;
  }}
"""


def reset_block(b: str) -> str:
    p = f"dut->m_axi_{b}_"
    return (f"  {p}ARREADY = 0; {p}RVALID = 0; std::memset(&{p}RDATA, 0, sizeof({p}RDATA));\n"
            f"  {p}RLAST = 0; {p}RID = 0; {p}RRESP = 0; {p}AWREADY = 1; {p}WREADY = 1;\n"
            f"  {p}BVALID = 0; {p}BID = 0; {p}BRESP = 0;\n")


def generate_tb(top: str, ports: list[dict], c_idx: int) -> str:
    """ports: [{bundle, arg, nbytes (data width bytes), size (buffer bytes), base, reg_lo, reg_hi}] in order."""
    n = len(ports)
    mem_init = "\n".join(
        f'  mem[{i}] = new MemRegion(0x{p["base"]:x}ULL, {p["size"]}ULL);' for i, p in enumerate(ports))
    loads = "\n".join(f'  load_file(data_dir + "/{p["arg"]}.bin", *mem[{i}]);' for i, p in enumerate(ports))
    regs = "\n".join(
        f'  ctrl_write(0x{p["reg_lo"]:02x}, (uint32_t)0x{p["base"]:x}ULL);\n'
        f'  ctrl_write(0x{p["reg_hi"]:02x}, (uint32_t)(0x{p["base"]:x}ULL >> 32));' for p in ports)
    dumps = "\n".join(f'  dump_file(out_dir + "/{p["arg"]}_out.bin", *mem[{i}]);' for i, p in enumerate(ports)
                      if i == c_idx)
    services = "".join(axi_block(p["bundle"], i, p["nbytes"]) for i, p in enumerate(ports))
    resets = "".join(reset_block(p["bundle"]) for p in ports)
    c = ports[c_idx]
    return f"""// Generated by tb_gen.py (AXI model ported from TAPA tb_verilator.cpp.j2, MIT). Top: {top}
#include "V{top}.h"
#include "verilated.h"
#include <chrono>
#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <deque>
#include <string>
#include <vector>

class MemRegion {{
 public:
  MemRegion(uint64_t base, size_t size) : base_(base), data_(size) {{}}
  uint64_t base() const {{ return base_; }}
  size_t size() const {{ return data_.size(); }}
  uint8_t* data() {{ return data_.data(); }}
  void read(uint64_t addr, void* buf, size_t n) const {{
    auto* d = reinterpret_cast<uint8_t*>(buf);
    for (size_t i = 0; i < n; i++) {{ const uint64_t o = addr + i - base_; d[i] = o < data_.size() ? data_[o] : 0; }}
  }}
  void write(uint64_t addr, const void* buf, const void* strb_ptr, size_t n) {{
    auto* s = reinterpret_cast<const uint8_t*>(buf);
    auto* st = reinterpret_cast<const uint8_t*>(strb_ptr);
    for (size_t i = 0; i < n; i++) {{
      const uint64_t o = addr + i - base_;
      if (o < data_.size() && (st[i / 8] & (1 << (i % 8)))) data_[o] = s[i];
    }}
  }}
 private:
  uint64_t base_;
  std::vector<uint8_t> data_;
}};

struct AxiReadReq {{ uint64_t addr; uint8_t len; uint32_t id; uint8_t beat; }};
struct AxiWriteReq {{ uint64_t addr; uint32_t id; uint8_t beat; }};
static constexpr int kMaxOutstanding = 16;
static constexpr int kNPorts = {n};
static constexpr int kCIdx = {c_idx};
static V{top}* dut;
static MemRegion* mem[kNPorts];
static std::deque<AxiReadReq> rd_q[kNPorts];
static std::deque<AxiWriteReq> wr_q[kNPorts];
static std::deque<uint32_t> b_q[kNPorts];

// ---- early check of C (port {c["bundle"]}, arg {c["arg"]}) against the golden ----
static std::vector<float> golden;
static std::vector<uint8_t> c_written;   // per fp32 element: written at least once
static bool c_was_read = false, c_rewritten = false;
static uint64_t c_first_writes = 0, c_early_bad = 0, cycle = 0;
static long long first_bad_idx = -1;
static uint64_t early_stop_after = 0;   // 0 = never stop early

static void check_c_write(uint64_t addr, const void* strb_ptr, size_t n) {{
  auto* st = reinterpret_cast<const uint8_t*>(strb_ptr);
  const uint64_t base = mem[kCIdx]->base();
  for (size_t e = 0; e < n / 4; e++) {{
    const uint64_t o = addr + e * 4 - base;
    if (o + 4 > mem[kCIdx]->size() || ((st[(e * 4) / 8] >> ((e * 4) % 8)) & 0xF) == 0) continue;
    const uint64_t idx = o / 4;
    if (c_written[idx]) {{ c_rewritten = true; continue; }}
    c_written[idx] = 1;
    c_first_writes++;
    float v; std::memcpy(&v, mem[kCIdx]->data() + o, 4);
    if (std::fabs(golden[idx] - v) > 0.001) {{
      if (c_early_bad++ == 0) {{
        first_bad_idx = (long long)idx;
        std::fprintf(stderr, "VCOSIM_EARLY_MISMATCH cycle=%llu idx=%llu golden=%g got=%g\\n",
                     (unsigned long long)cycle, (unsigned long long)idx, golden[idx], v);
      }}
    }}
  }}
}}

static void load_file(const std::string& path, MemRegion& m) {{
  FILE* f = std::fopen(path.c_str(), "rb");
  if (!f) {{ std::perror(path.c_str()); std::exit(3); }}
  const size_t got = std::fread(m.data(), 1, m.size(), f);
  std::fclose(f);
  if (got != m.size()) {{ std::fprintf(stderr, "short read %s: %zu of %zu\\n", path.c_str(), got, m.size()); std::exit(3); }}
}}
static void dump_file(const std::string& path, MemRegion& m) {{
  FILE* f = std::fopen(path.c_str(), "wb");
  if (!f || std::fwrite(m.data(), 1, m.size(), f) != m.size()) {{ std::perror(path.c_str()); std::exit(3); }}
  std::fclose(f);
}}

static void tick() {{ dut->ap_clk = 1; dut->eval(); dut->ap_clk = 0; dut->eval(); }}

static void service_all_axi() {{
{services}}}

static void ctrl_write(uint32_t addr, uint32_t data) {{
  dut->s_axi_control_AWVALID = 1; dut->s_axi_control_AWADDR = addr;
  dut->s_axi_control_WVALID = 1; dut->s_axi_control_WDATA = data; dut->s_axi_control_WSTRB = 0xF;
  dut->s_axi_control_BREADY = 1;
  for (int i = 0; i < 20; ++i) {{ service_all_axi(); tick(); if (dut->s_axi_control_BVALID) break; }}
  dut->s_axi_control_AWVALID = 0; dut->s_axi_control_WVALID = 0; dut->s_axi_control_BREADY = 0;
  service_all_axi(); tick();
}}

int main(int argc, char** argv) {{
  // usage: Vtop DATA_DIR OUT_DIR MAX_CYCLES HEARTBEAT EARLY_STOP_AFTER [+verilator args]
  if (argc < 6) {{ std::fprintf(stderr, "usage: %s DATA_DIR OUT_DIR MAX_CYCLES HEARTBEAT EARLY_STOP_AFTER\\n", argv[0]); return 2; }}
  const std::string data_dir = argv[1], out_dir = argv[2];
  const uint64_t max_cycles = std::strtoull(argv[3], nullptr, 10);
  const uint64_t heartbeat = std::strtoull(argv[4], nullptr, 10);
  early_stop_after = std::strtoull(argv[5], nullptr, 10);
  Verilated::commandArgs(argc, argv);
  dut = new V{top};
{mem_init}
{loads}
  {{
    const size_t nc = mem[kCIdx]->size() / 4;
    golden.resize(nc); c_written.assign(nc, 0);
    FILE* g = std::fopen((data_dir + "/C_golden.bin").c_str(), "rb");
    if (!g || std::fread(golden.data(), 4, nc, g) != nc) {{ std::fprintf(stderr, "cannot read golden\\n"); return 3; }}
    std::fclose(g);
  }}
  dut->ap_clk = 0; dut->ap_rst_n = 0;
  dut->s_axi_control_AWVALID = 0; dut->s_axi_control_WVALID = 0; dut->s_axi_control_ARVALID = 0;
  dut->s_axi_control_BREADY = 0; dut->s_axi_control_RREADY = 0;
{resets}  for (int i = 0; i < 10; ++i) tick();
  dut->ap_rst_n = 1;
  for (int i = 0; i < 5; ++i) tick();
  ctrl_write(0x04, 1);   // GIE
  ctrl_write(0x08, 1);   // IER: ap_done
{regs}
  ctrl_write(0x00, 1);   // ap_start
  std::fprintf(stderr, "VCOSIM_START\\n");
  const auto t0 = std::chrono::steady_clock::now();
  auto secs = [&]() {{ return std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count(); }};
  int status = 1;   // 0 done, 1 cycle limit, 2 early stop
  for (cycle = 0; cycle < max_cycles; ++cycle) {{
    service_all_axi();
    tick();
    if (dut->__SYM__interrupt) {{ status = 0; break; }}
    if (heartbeat && cycle && cycle % heartbeat == 0) {{
      const double s = secs();
      std::fprintf(stderr, "VCOSIM_HEARTBEAT cycles=%llu wall_s=%.1f cycles_per_s=%.1f c_first_writes=%llu c_early_bad=%llu\\n",
                   (unsigned long long)cycle, s, cycle / (s > 0 ? s : 1), (unsigned long long)c_first_writes,
                   (unsigned long long)c_early_bad);
    }}
    if (early_stop_after && c_early_bad >= early_stop_after && !c_was_read && !c_rewritten) {{ status = 2; break; }}
  }}
  const double s = secs();
  std::fprintf(stderr, "VCOSIM_END status=%s cycles=%llu wall_s=%.1f c_read=%d c_rewritten=%d c_first_writes=%llu c_early_bad=%llu first_bad_idx=%lld\\n",
               status == 0 ? "done" : status == 1 ? "cycle_limit" : "early_stop", (unsigned long long)cycle, s,
               (int)c_was_read, (int)c_rewritten, (unsigned long long)c_first_writes,
               (unsigned long long)c_early_bad, first_bad_idx);
{dumps}
  dut->final();
  delete dut;
  return status;
}}
"""
